"""Run schema and quality checks for the synthetic credit portfolio data."""

from __future__ import annotations

from datetime import datetime, timezone

import pandas as pd

from config import AUDIT_DIR, RAW_DIR, VALID_RISK_RATINGS, ensure_directories

REQUIRED_COLUMNS = {
    "customers": [
        "customer_id",
        "customer_name",
        "country",
        "region",
        "industry",
        "company_size",
        "onboarding_date",
        "active_flag",
    ],
    "credit_exposures": [
        "exposure_id",
        "customer_id",
        "reporting_month",
        "credit_limit",
        "current_exposure",
        "outstanding_amount",
        "overdue_amount",
        "days_past_due",
        "collateral_value",
        "exposure_status",
        "currency",
    ],
    "risk_ratings": [
        "customer_id",
        "reporting_month",
        "risk_rating",
        "previous_risk_rating",
        "rating_score",
        "probability_of_default_proxy",
        "rating_outlook",
    ],
    "default_events": [
        "default_event_id",
        "customer_id",
        "event_date",
        "default_flag",
        "default_reason",
        "recovery_amount",
        "loss_amount",
    ],
    "payments": [
        "payment_id",
        "customer_id",
        "payment_date",
        "payment_amount",
        "expected_payment_amount",
        "days_late",
    ],
    "macroeconomic_scenarios": [
        "scenario_id",
        "scenario_name",
        "pd_shock",
        "lgd_shock",
        "exposure_shock",
        "description",
    ],
}


def load_raw_tables() -> dict[str, pd.DataFrame]:
    """Load raw CSV tables generated by the synthetic data module."""
    return {table: pd.read_csv(RAW_DIR / f"{table}.csv") for table in REQUIRED_COLUMNS}


def _result(
    check_name: str,
    table_name: str,
    records_checked: int,
    failed_records: int,
    severity: str = "High",
) -> dict[str, object]:
    failure_rate = failed_records / records_checked if records_checked else 0
    return {
        "check_name": check_name,
        "table_name": table_name,
        "status": "Pass" if failed_records == 0 else "Fail",
        "records_checked": int(records_checked),
        "failed_records": int(failed_records),
        "failure_rate": round(failure_rate, 6),
        "severity": severity,
        "check_timestamp": datetime.now(timezone.utc).isoformat(),
    }


def validate_tables(tables: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Return a data quality report covering schema, key, range, and domain checks."""
    checks: list[dict[str, object]] = []

    for table_name, required_columns in REQUIRED_COLUMNS.items():
        df = tables[table_name]
        missing = [column for column in required_columns if column not in df.columns]
        checks.append(_result("required_columns_exist", table_name, len(required_columns), len(missing), "Critical"))
        for column in required_columns:
            if column in df.columns:
                checks.append(
                    _result(
                        f"no_nulls_in_{column}",
                        table_name,
                        len(df),
                        int(df[column].isna().sum()),
                        "High",
                    )
                )

    customers = tables["customers"]
    exposures = tables["credit_exposures"]
    ratings = tables["risk_ratings"]
    defaults = tables["default_events"]
    payments = tables["payments"]

    checks.append(_result("no_duplicate_customer_ids", "customers", len(customers), int(customers["customer_id"].duplicated().sum()), "Critical"))
    checks.append(_result("no_duplicate_exposure_ids", "credit_exposures", len(exposures), int(exposures["exposure_id"].duplicated().sum()), "Critical"))

    valid_customers = set(customers["customer_id"])
    for table_name, df in {
        "credit_exposures": exposures,
        "risk_ratings": ratings,
        "default_events": defaults,
        "payments": payments,
    }.items():
        failed = int((~df["customer_id"].isin(valid_customers)).sum())
        checks.append(_result("customer_ids_match_customer_master", table_name, len(df), failed, "Critical"))

    numeric_non_negative = {
        "credit_limit": exposures["credit_limit"],
        "current_exposure": exposures["current_exposure"],
        "outstanding_amount": exposures["outstanding_amount"],
        "overdue_amount": exposures["overdue_amount"],
        "days_past_due": exposures["days_past_due"],
        "payment_amount": payments["payment_amount"],
        "expected_payment_amount": payments["expected_payment_amount"],
        "loss_amount": defaults["loss_amount"],
        "recovery_amount": defaults["recovery_amount"],
    }
    for column, series in numeric_non_negative.items():
        table = "credit_exposures" if column in exposures.columns else "payments" if column in payments.columns else "default_events"
        checks.append(_result(f"{column}_is_non_negative", table, len(series), int((series < 0).sum()), "Critical"))

    checks.append(
        _result(
            "overdue_amount_does_not_exceed_outstanding_amount",
            "credit_exposures",
            len(exposures),
            int((exposures["overdue_amount"] > exposures["outstanding_amount"]).sum()),
            "Critical",
        )
    )
    utilization = exposures["current_exposure"] / exposures["credit_limit"].replace(0, pd.NA)
    checks.append(_result("exposure_utilization_is_reasonable", "credit_exposures", len(exposures), int((utilization > 1.5).sum()), "Medium"))
    checks.append(_result("risk_ratings_are_valid", "risk_ratings", len(ratings), int((~ratings["risk_rating"].isin(VALID_RISK_RATINGS)).sum()), "Critical"))
    checks.append(_result("previous_risk_ratings_are_valid", "risk_ratings", len(ratings), int((~ratings["previous_risk_rating"].isin(VALID_RISK_RATINGS)).sum()), "Critical"))
    checks.append(_result("default_flags_are_valid", "default_events", len(defaults), int((~defaults["default_flag"].isin([0, 1, True, False])).sum()), "Critical"))
    checks.append(_result("active_flags_are_valid", "customers", len(customers), int((~customers["active_flag"].isin([0, 1, True, False])).sum()), "Critical"))

    for table_name, df, column in [
        ("credit_exposures", exposures, "reporting_month"),
        ("risk_ratings", ratings, "reporting_month"),
        ("default_events", defaults, "event_date"),
        ("payments", payments, "payment_date"),
    ]:
        parsed = pd.to_datetime(df[column], errors="coerce")
        checks.append(_result(f"{column}_is_valid_date", table_name, len(df), int(parsed.isna().sum()), "High"))

    return pd.DataFrame(checks)


def main() -> None:
    ensure_directories()
    report = validate_tables(load_raw_tables())
    output_path = AUDIT_DIR / "data_quality_report.csv"
    report.to_csv(output_path, index=False)
    failed = int((report["status"] == "Fail").sum())
    print(f"Data quality report saved to {output_path} ({failed} failed checks)")


if __name__ == "__main__":
    main()
